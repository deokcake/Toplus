"""2차 감수 기록: 원문항 해설(X), 문항별 풀이 순서(st + 유형별 칸), 재감수 결과(RV).
X(급, 번호, r=핵심 규칙, n=[보기별 해설 5개], k=정답 판단(생략 가능), pre=[보기 앞 줄들],
  st="① … {0} … → ② … {a}", R=(칸 값들), B=(...), C=..., D=..., E=..., F=...)
  - st의 {0},{1}…은 문항마다 다른 단서, {a}는 정답 보기 글, {n}은 정답 번호(①~⑤)
  - 유형 칸 값이 문자열이면 그 문항만 통째로 다른 풀이 순서
RV(급, 번호, "BC…", v=새 판정(생략 = 유지), why=사유, fix=수정 방향, fx=True(수정 예시를 고쳤음))"""
EX, REV = {}, {}
def X(g, n, /, **kw):
    assert (g, n) not in EX, f"중복 {g}-{n}"
    EX[(g, n)] = kw
def RV(g, n, ts, /, **kw):
    for t in ts:
        REV.setdefault((g, n, t), []).append(kw)
